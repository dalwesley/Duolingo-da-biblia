/**
 * Banco editorial V2 — Gênesis 12–50 (STWAY).
 * Semente = observar | Caminhada = compreender | Profundezas = interpretar/conectar
 */

const SHORT = { semente: 'sem', caminhada: 'cam', profundezas: 'pro' };

function q(section, diff, n, fields) {
  const {
    question,
    options,
    correct,
    ok,
    wrong,
    verseRef,
    skill,
    type = 'choice',
    learningObjective,
    evidence,
    passageText,
    template,
  } = fields;
  return {
    id: `genesis-12-50-${SHORT[diff]}-${section}-${String(n).padStart(2, '0')}`,
    trail: 'genesis-12-50',
    difficulty: diff,
    section,
    type,
    skill,
    question,
    prompt: question,
    cue: question,
    options: options.map(([id, text]) => ({ id, text })),
    correctOptionId: correct,
    correctAnswer: correct,
    feedbackCorrect: ok,
    feedbackWrong: wrong,
    verseRef,
    learningObjective,
    evidence: evidence || [verseRef],
    ...(passageText ? { passageText } : {}),
    ...(template ? { template } : {}),
  };
}

function pack(section, levels) {
  const skillMap = { semente: 'observe', caminhada: 'understand' };
  const out = [];
  for (const [diff, items] of Object.entries(levels)) {
    items.forEach((fields, i) => {
      const skill =
        fields.skill ||
        skillMap[diff] ||
        (i % 2 === 0 ? 'interpret' : 'connect');
      out.push(q(section, diff, i + 1, { ...fields, skill }));
    });
  }
  return out;
}

