def q(section, diff, skill, typ, nn, verse_ref, lo, evidence, question, ok, wrong, options, correct, passage, **extra):
    short = {"semente": "sem", "caminhada": "cam", "profundezas": "pro"}[diff]
    item = {
        "difficulty": diff,
        "skill": skill,
        "verseRef": verse_ref,
        "learningObjective": lo,
        "evidence": evidence,
        "type": typ,
        "question": question,
        "prompt": question,
        "cue": question,
        "feedbackCorrect": ok,
        "feedbackWrong": wrong,
        "options": options,
        "correctOptionId": correct,
        "correctAnswer": correct,
        "passageText": passage,
        "trail": TRAIL,
        "section": section,
        "id": f"{TRAIL}-{short}-{section}-{nn}",
    }
    item.update(extra)
    assert len(ok) <= 100, (len(ok), ok)
    if typ == "choice":
        for o in options:
            assert len(o["text"]) <= 90, (len(o["text"]), o["text"])
    if typ == "tap":
        for o in options:
            assert o["text"].lower() in passage.lower(), (o["text"], section, nn, diff)
    return item


def tf():
    return [{"id": "true", "text": "Verdadeiro"}, {"id": "false", "text": "Falso"}]


def opts(*pairs):
    return [{"id": i, "text": t} for i, t in pairs]


def mission(section, verse, passage, lo, evidence, specs):
    out = []
    for s in specs:
        extra = {k: s[k] for k in ("template", "correctOrder", "passageA", "passageB") if k in s}
        out.append(
            q(
                section, s["diff"], s["skill"], s["type"], s["nn"], verse, lo, evidence,
                s["question"], s["ok"], s["wrong"], s["options"], s["correct"], passage, **extra,
            )
        )
    return out


def six(section, verse, passage, lo, evidence, insight, sem, cam, pro):
    """Monta 18 perguntas a partir de dicts sem/cam/pro com chaves tipadas."""
    specs = []
    for diff, skill, pack in (
        ("semente", "observe", sem),
        ("caminhada", "understand", cam),
        ("profundezas", "interpret", pro),
    ):
        # 01 true_false
        specs.append(dict(
            diff=diff, skill=skill, type="true_false", nn="01",
            question=pack["tf_q"], ok=pack["tf_ok"], wrong=pack["tf_wrong"],
            options=tf(), correct=pack["tf_correct"],
        ))
        # 02 tap
        specs.append(dict(
            diff=diff, skill=skill, type="tap", nn="02",
            question=pack["tap_q"], ok=pack["tap_ok"], wrong=pack["tap_wrong"],
            options=opts(*pack["tap_opts"]), correct=pack["tap_correct"],
            template=pack["tap_tpl"],
        ))
        # 03 choice
        specs.append(dict(
            diff=diff, skill=skill, type="choice", nn="03",
            question=pack["ch_q"], ok=pack["ch_ok"], wrong=pack["ch_wrong"],
            options=opts(*pack["ch_opts"]), correct=pack["ch_correct"],
        ))
        # 04 order
        specs.append(dict(
            diff=diff, skill=skill, type="order", nn="04",
            question=pack["or_q"], ok=pack["or_ok"], wrong=pack["or_wrong"],
            options=opts(*pack["or_opts"]), correct="a", correctOrder=["a", "b", "c"],
        ))
        # 05 complete
        specs.append(dict(
            diff=diff, skill=skill, type="complete", nn="05",
            question=pack["co_q"], ok=pack["co_ok"], wrong=pack["co_wrong"],
            options=opts(*pack["co_opts"]), correct=pack["co_correct"],
            template=pack["co_tpl"],
        ))
        # 06 connect
        specs.append(dict(
            diff=diff, skill=skill, type="connect", nn="06",
            question=f"O que {verse} comunica que se liga a este contexto?",
            ok=pack["cn_ok"], wrong=pack["cn_wrong"],
            options=opts(*pack["cn_opts"]), correct=pack["cn_correct"],
            passageA=pack["cn_a"],
            passageB={"ref": "Contexto", "text": insight},
        ))
    return mission(section, verse, passage, lo, evidence, specs)


